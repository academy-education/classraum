#!/usr/bin/env node
/**
 * make-exclusions-b3.mjs: EXCLUSIONS-science.txt for batch 3 = batch 2's list (ACT files + live/staged act and map
 * science rows read 2026-10-31 + pilot + batch-1 items) plus every batch-2 item (224; batch-2 topics stay excluded).
 * Reads files only, no DB. Same line format as make-exclusions.mjs. Exit 2 if either input is missing or short.
 *
 *   node scripts/study-bank/map-v2-work/science-b3/make-exclusions-b3.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
const HERE = dirname(fileURLToPath(import.meta.url)), ROOT = join(HERE, '../../../..')
const die = m => { console.error('REFUSING: ' + m); process.exit(2) }
const prev = readFileSync(join(HERE, '../science-b2/EXCLUSIONS-science.txt'), 'utf8').split('\n').filter(l => l && !l.startsWith('#'))
if (prev.length < 600) die(`batch-2 exclusions hold only ${prev.length} lines`)
const words = s => String(s ?? '').replace(/\s+/g, ' ').trim().split(' ').slice(0, 30).join(' ')
const seen = new Set(prev.map(l => l.toLowerCase())), add = []
let n = 0
for (const c of ['L5', 'L6', 'L7', 'L8', 'P5', 'P6', 'P7', 'P8', 'E5', 'E6', 'E7', 'E8']) {
  const f = join(ROOT, 'scratchpad/map-science-b2', c, 'items.json')
  if (!existsSync(f)) die(`missing ${f}`)
  for (const it of JSON.parse(readFileSync(f, 'utf8'))) {
    if (it.empty) continue
    n++
    const line = `map-science:${it.id} | ${(it.names_used ?? []).join(', ').replace(/\|/g, '/')} | ${words([it.passage, it.prompt].filter(Boolean).join(' ')).replace(/\|/g, '/')}`
    if (!seen.has(line.toLowerCase())) { seen.add(line.toLowerCase()); add.push(line) }
  }
}
if (n !== 224) die(`read ${n} batch-2 items, expected 224`)
writeFileSync(join(HERE, 'EXCLUSIONS-science.txt'), `# generated by science-b3/make-exclusions-b3.mjs; ${prev.length} lines from science-b2/EXCLUSIONS-science.txt + ${add.length} batch-2 items\n` + [...prev, ...add].join('\n') + '\n')
console.log(`wrote EXCLUSIONS-science.txt: ${prev.length} batch-2 lines + ${add.length} batch-2 items = ${prev.length + add.length}`)
