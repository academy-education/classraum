#!/usr/bin/env node
/**
 * make-exclusions-b3full.mjs: EXCLUSIONS-science.txt for the FULL batch 3 = pilot 2's list (batch 2's 632 lines + all 224
 * batch-2 items + 24 pilot-1 items) plus every pilot-2 item (24; pilot-2 topics stay excluded). Files only, no DB.
 * Same line format as make-exclusions.mjs. Exit 2 if an input is missing or short.
 *
 *   node scripts/study-bank/map-v2-work/science-b3full/make-exclusions-b3full.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
const HERE = dirname(fileURLToPath(import.meta.url)), ROOT = join(HERE, '../../../..')
const die = m => { console.error('REFUSING: ' + m); process.exit(2) }
const prev = readFileSync(join(HERE, '../science-b3p2/EXCLUSIONS-science.txt'), 'utf8').split('\n').filter(l => l && !l.startsWith('#'))
if (prev.length < 875) die(`pilot-2 exclusions hold only ${prev.length} lines`)
const words = s => String(s ?? '').replace(/\s+/g, ' ').trim().split(' ').slice(0, 30).join(' ')
const seen = new Set(prev.map(l => l.toLowerCase())), add = []
let n = 0
for (const c of ['L', 'P', 'E']) {
  const f = join(ROOT, 'scratchpad/map-science-b3p2', c, 'items.json')
  if (!existsSync(f)) die(`missing ${f}`)
  for (const it of JSON.parse(readFileSync(f, 'utf8'))) {
    if (it.empty) continue
    n++
    const line = `map-science:${it.id} | ${(it.names_used ?? []).join(', ').replace(/\|/g, '/')} | ${words([it.passage, it.prompt].filter(Boolean).join(' ')).replace(/\|/g, '/')}`
    if (!seen.has(line.toLowerCase())) { seen.add(line.toLowerCase()); add.push(line) }
  }
}
if (n !== 24) die(`read ${n} pilot-2 items, expected 24`)
writeFileSync(join(HERE, 'EXCLUSIONS-science.txt'), `# generated by science-b3full/make-exclusions-b3full.mjs; ${prev.length} lines from science-b3p2/EXCLUSIONS-science.txt + ${add.length} pilot-2 items\n` + [...prev, ...add].join('\n') + '\n')
console.log(`wrote EXCLUSIONS-science.txt: ${prev.length} pilot-2 lines + ${add.length} pilot-2 items = ${prev.length + add.length}`)
