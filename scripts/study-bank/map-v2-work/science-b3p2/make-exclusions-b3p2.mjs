#!/usr/bin/env node
/**
 * make-exclusions-b3p2.mjs: EXCLUSIONS-science.txt for batch 3 PILOT 2 = batch 3's list (batch 2's 632 lines + all 224
 * batch-2 items) plus every batch-3 pilot-1 item (24; pilot-1 topics stay excluded).
 * Reads files only, no DB. Same line format as make-exclusions.mjs. Exit 2 if either input is missing or short.
 *
 *   node scripts/study-bank/map-v2-work/science-b3p2/make-exclusions-b3p2.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
const HERE = dirname(fileURLToPath(import.meta.url)), ROOT = join(HERE, '../../../..')
const die = m => { console.error('REFUSING: ' + m); process.exit(2) }
const prev = readFileSync(join(HERE, '../science-b3/EXCLUSIONS-science.txt'), 'utf8').split('\n').filter(l => l && !l.startsWith('#'))
if (prev.length < 850) die(`batch-3 exclusions hold only ${prev.length} lines`)
const words = s => String(s ?? '').replace(/\s+/g, ' ').trim().split(' ').slice(0, 30).join(' ')
const seen = new Set(prev.map(l => l.toLowerCase())), add = []
let n = 0
for (const c of ['L', 'P', 'E']) {
  const f = join(ROOT, 'scratchpad/map-science-b3', c, 'items.json')
  if (!existsSync(f)) die(`missing ${f}`)
  for (const it of JSON.parse(readFileSync(f, 'utf8'))) {
    if (it.empty) continue
    n++
    const line = `map-science:${it.id} | ${(it.names_used ?? []).join(', ').replace(/\|/g, '/')} | ${words([it.passage, it.prompt].filter(Boolean).join(' ')).replace(/\|/g, '/')}`
    if (!seen.has(line.toLowerCase())) { seen.add(line.toLowerCase()); add.push(line) }
  }
}
if (n !== 24) die(`read ${n} pilot-1 items, expected 24`)
writeFileSync(join(HERE, 'EXCLUSIONS-science.txt'), `# generated by science-b3p2/make-exclusions-b3p2.mjs; ${prev.length} lines from science-b3/EXCLUSIONS-science.txt + ${add.length} batch-3 pilot-1 items\n` + [...prev, ...add].join('\n') + '\n')
console.log(`wrote EXCLUSIONS-science.txt: ${prev.length} batch-3 lines + ${add.length} pilot-1 items = ${prev.length + add.length}`)
