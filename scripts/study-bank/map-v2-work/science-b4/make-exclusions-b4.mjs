#!/usr/bin/env node
/**
 * make-exclusions-b4.mjs: EXCLUSIONS-science.txt for MAP Science batch 4 = batch 3 full's list (live rows as of b3 full,
 * batch 2, both b3 pilots) plus every batch-3-full item (230: survivors are now live, drops stay excluded). Files only,
 * no DB (the live snapshot is covered by probe-live-b4.mjs). Same line format. Exit 2 if an input is missing or short.
 *
 *   node scripts/study-bank/map-v2-work/science-b4/make-exclusions-b4.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
const HERE = dirname(fileURLToPath(import.meta.url))
const die = m => { console.error('REFUSING: ' + m); process.exit(2) }
const prev = readFileSync(join(HERE, '../science-b3full/EXCLUSIONS-science.txt'), 'utf8').split('\n').filter(l => l && !l.startsWith('#'))
if (prev.length < 899) die(`b3-full exclusions hold only ${prev.length} lines`)
const words = s => String(s ?? '').replace(/\s+/g, ' ').trim().split(' ').slice(0, 30).join(' ')
const seen = new Set(prev.map(l => l.toLowerCase())), add = []
let n = 0
for (const c of ['L', 'P', 'E']) {
  const f = join(HERE, '../science-b3full/items', `${c}.json`)
  if (!existsSync(f)) die(`missing ${f}`)
  for (const it of JSON.parse(readFileSync(f, 'utf8'))) {
    if (it.empty) continue
    n++
    const line = `map-science:${it.id} | ${(it.names_used ?? []).join(', ').replace(/\|/g, '/')} | ${words([it.passage, it.prompt].filter(Boolean).join(' ')).replace(/\|/g, '/')}`
    if (!seen.has(line.toLowerCase())) { seen.add(line.toLowerCase()); add.push(line) }
  }
}
if (n !== 230) die(`read ${n} b3-full items, expected 230`)
writeFileSync(join(HERE, 'EXCLUSIONS-science.txt'), `# generated by science-b4/make-exclusions-b4.mjs; ${prev.length} lines from science-b3full/EXCLUSIONS-science.txt + ${add.length} batch-3-full items\n` + [...prev, ...add].join('\n') + '\n')
console.log(`wrote EXCLUSIONS-science.txt: ${prev.length} + ${add.length} = ${prev.length + add.length}`)
