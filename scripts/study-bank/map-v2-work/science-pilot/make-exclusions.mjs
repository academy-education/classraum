#!/usr/bin/env node
/**
 * make-exclusions.mjs: writes EXCLUSIONS-science.txt, one line per distinct science stimulus already authored in this
 * repo, as `source | title | first 30 words`. Authors grep it before choosing a subject or an invented name.
 * sci-check.mjs reads it for its near-duplicate check.
 *
 * Reads only files on disk (no DB): every scripts/study-bank/act-science*.batch.json (ACT Science, live + staged +
 * dropped cohorts, 780 rows on 2026-10-27), plus any MAP science author file passed on the command line (a later batch
 * passes the earlier batches' items so they cannot be re-authored).
 *
 *   node scripts/study-bank/map-v2-work/science-pilot/make-exclusions.mjs [--live] [earlier-map-science.json ...]
 *
 * --live also READS (never writes) every act/science and map/science row in study_item_bank, live and staged, paged
 * with the server count asserted, so a cohort inserted from a file that is not on disk still reaches the list.
 * 2026-10-27: --live read 600 act/science rows and added 0 new stimuli; every live passage is in the 26 files.
 *
 * Exits 2 if it reads zero ACT science stimuli: a missing corpus must not silently become "no duplicates".
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const SB = join(HERE, '../..')
const words = s => String(s ?? '').replace(/\s+/g, ' ').trim().split(' ').slice(0, 30).join(' ')
const seen = new Set(), lines = []
const add = (src, title, text) => {
  const k = `${title}|${words(text)}`.toLowerCase()
  if (seen.has(k) || !String(text ?? '').trim()) return
  seen.add(k); lines.push(`${src} | ${String(title ?? '').replace(/\|/g, '/')} | ${words(text).replace(/\|/g, '/')}`)
}
const files = readdirSync(SB).filter(f => /^act-science.*\.batch\.json$/.test(f)).sort()
for (const f of files) {
  const items = JSON.parse(readFileSync(join(SB, f), 'utf8'))
  for (const it of items) add(f.replace('.batch.json', ''), it.passage_title ?? it.passage_id, it.passage)
}
if (process.argv.includes('--live')) {
  const { createClient } = await import('@supabase/supabase-js')
  const env = Object.fromEntries(readFileSync(join(SB, '../../.env.local'), 'utf8').split('\n')
    .filter(l => l.includes('=') && !l.startsWith('#')).map(l => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1).trim()]))
  const db = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } })
  for (const fam of ['act', 'map']) {
    const { count, error: ce } = await db.from('study_item_bank').select('id', { count: 'exact', head: true }).eq('family', fam).eq('section', 'science')
    if (ce) { console.error(ce.message); process.exit(2) }
    const rows = []
    for (let f = 0; ; f += 1000) {
      const { data, error } = await db.from('study_item_bank').select('id,cohort,item').eq('family', fam).eq('section', 'science').order('id').range(f, f + 999)
      if (error) { console.error(error.message); process.exit(2) }
      rows.push(...data); if (data.length < 1000) break
    }
    if (rows.length !== count) { console.error(`REFUSING: read ${rows.length} ${fam}/science rows, server count ${count}`); process.exit(2) }
    for (const r of rows) add(`${fam}:${r.cohort}`, r.item?.passage_title ?? '', [r.item?.passage, fam === 'map' ? r.item?.prompt : ''].filter(Boolean).join(' '))
    console.log(`  read ${rows.length} ${fam}/science rows (server count ${count})`)
  }
}
const act = lines.length
for (const f of process.argv.slice(2).filter(a => !a.startsWith('--'))) {
  for (const it of JSON.parse(readFileSync(f, 'utf8'))) {
    if (it.empty) continue
    add(`map-science:${it.id}`, (it.names_used ?? []).join(', '), [it.passage, it.prompt].filter(Boolean).join(' '))
  }
}
if (!act) { console.error(`REFUSING: read 0 ACT science stimuli from ${files.length} files`); process.exit(2) }
const out = join(HERE, 'EXCLUSIONS-science.txt')
writeFileSync(out, `# generated by make-exclusions.mjs; ${act} ACT science stimuli from ${files.length} files, ${lines.length - act} MAP science items\n` + lines.join('\n') + '\n')
console.log(`wrote ${out}: ${act} ACT science stimuli (${files.length} files), ${lines.length - act} MAP science`)
