#!/usr/bin/env node
/**
 * make-name-endings.mjs: writes name-endings.json, the BASE RATE of two-letter endings among English proper names, which
 * sci-check's recalibrated NAMETPL compares an area's invented names against (MAP-SCIENCE-B3-FULL.prereg.md). Source:
 * /usr/share/dict/propernames (macOS, 1308 given names; independent of every bank item). Run once; the JSON is the input
 * sci-check reads, so a machine without the dictionary still checks reproducibly. Exit 2 if the source is missing/short.
 *
 *   node scripts/study-bank/map-v2-work/science-pilot/make-name-endings.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
const SRC = '/usr/share/dict/propernames', OUT = join(dirname(fileURLToPath(import.meta.url)), 'name-endings.json')
if (!existsSync(SRC)) { console.error(`REFUSING: no ${SRC}`); process.exit(2) }
const names = readFileSync(SRC, 'utf8').split('\n').map(s => s.trim()).filter(s => /^[A-Z][a-z]{2,}$/.test(s))
if (names.length < 1000) { console.error(`REFUSING: ${names.length} names read from ${SRC}`); process.exit(2) }
const c = {}; for (const n of names) c[n.slice(-2)] = (c[n.slice(-2)] ?? 0) + 1
const sorted = Object.fromEntries(Object.entries(c).sort((a, b) => b[1] - a[1]))
writeFileSync(OUT, JSON.stringify({ _source: SRC, _n: names.length, _note: 'two-letter ending counts of English given names; generated by make-name-endings.mjs', counts: sorted }, null, 1) + '\n')
console.log(`wrote ${OUT}: ${names.length} names, ${Object.keys(c).length} endings; top ${Object.entries(sorted).slice(0, 8).map(([e, n]) => `-${e} ${n}`).join(', ')}`)
