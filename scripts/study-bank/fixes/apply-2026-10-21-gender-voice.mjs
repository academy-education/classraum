#!/usr/bin/env node
/**
 * apply-2026-10-21-gender-voice.mjs [--write | --rollback]
 *
 * NOT APPROVED. Wording changes on live rows need the owner's sign-off
 * (REGISTER §3). Dry run by default; --write is for after that sign-off.
 *
 * The listening player voices dialogue speakers by order of first appearance:
 * A = nova (female), B = onyx (male), then shimmer, echo
 * (ListeningAudioPlayer.tsx DIALOGUE_VOICE_ROTATION). 53 live TOEFL Listening
 * dialogue items in 28 conversations refer to a speaker with the opposite
 * gender's pronoun. Every one of the 112 gendered dialogue items was read; the
 * plan (gender-voice-2026-10-21.plan.json) holds the literal from/to text of
 * every changed field, with the speaker/voice reading per item. Generated by a
 * pronoun flip, then corrected by hand where the flip was wrong:
 *   - 4 items are scoped, not flipped: one party is already right
 *     (8e0eaedd her = Benedikta; f4550ae0 explanation only; bc261e54 one word;
 *     c077875b librarian only, the student's she stays)
 *   - 2 rationales are kept: the author's pronoun there already names the
 *     staff member correctly (3526c7a8 r[2], 2b859327 r[1])
 *   - af834814: "told his there" / "Him only" grammar fixed
 *
 * Only prompt, choices, correct_answer, explanation and distractor_rationales
 * change (asserted). The key stays the same option by index (asserted), and
 * every rationale that named a choice still names one (asserted).
 *
 * content_sha (migration 076) = md5(prompt, passage, correct_answer, choices).
 * 52 of the 53 items change prompt/choices/key, so their bound reviews and
 * attacks go STALE. f4550ae0 changes its explanation only and stays fresh.
 * Counts are printed.
 *
 * Snapshot (full rows) is written on the first run, dry run included, never
 * overwritten. --write refuses if any live row no longer matches it.
 * --rollback restores `item` from the snapshot.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { createClient } from '@supabase/supabase-js'

const D = new URL('.', import.meta.url).pathname
const PLAN = JSON.parse(readFileSync(D + 'gender-voice-2026-10-21.plan.json', 'utf8'))
const SNAP = D + 'snapshot-2026-10-21-gender-voice.json'
const WRITE = process.argv.includes('--write')
const ROLLBACK = process.argv.includes('--rollback')
// The repo root's .env.local; a worktree under .claude/worktrees/ has none, so
// fall back to the main checkout's.
const ENV = [D + '../../../.env.local', D + '../../../../../../.env.local'].find(existsSync)
if (!ENV) throw new Error('no .env.local found')
const env = Object.fromEntries(readFileSync(ENV, 'utf8').split('\n')
  .filter(l => l.includes('=') && !l.startsWith('#'))
  .map(l => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1).trim()]))
const db = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } })
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b)

const IDS = PLAN.map(p => p.id)
if (new Set(IDS).size !== 53) throw new Error(`expected 53 distinct ids, got ${new Set(IDS).size}`)
const SHA_FIELD = /^(prompt|choices\[\d+\]|correct_answer)$/
const shaMoves = p => p.edits.some(e => SHA_FIELD.test(e.field))

async function rowsById(ids) {
  const { data, error } = await db.from('study_item_bank').select('*').in('id', ids)
  if (error) throw new Error(error.message)
  if (data.length !== ids.length) throw new Error(`expected ${ids.length} rows, got ${data.length}`)
  return Object.fromEntries(data.map(r => [r.id, r]))
}
async function bindings(ids) {
  const c = async (t) => {
    const { data, error } = await db.from(t).select('id,item_id').in('item_id', ids)
    if (error) throw new Error(`${t}: ${error.message}`); return data.length
  }
  return { reviews: await c('study_item_reviews'), reviewsFresh: await c('study_item_reviews_fresh'),
    attacks: await c('study_item_attacks'), attacksFresh: await c('study_item_attacks_fresh') }
}

if (ROLLBACK) {
  const snap = JSON.parse(readFileSync(SNAP, 'utf8'))
  for (const r of snap) {
    const { error } = await db.from('study_item_bank').update({ item: r.item }).eq('id', r.id)
    if (error) throw new Error(`${r.id}: ${error.message}`)
  }
  const back = await rowsById(snap.map(r => r.id))
  const bad = snap.filter(r => !same(back[r.id].item, r.item))
  console.log(`rolled back ${snap.length} rows from ${SNAP}; ${bad.length} mismatched after re-read`)
  process.exit(bad.length ? 1 : 0)
}

function get(o, field) {
  const m = field.match(/^(\w+)(?:\[(\d+)\](?:\.(\w+))?)?$/)
  if (!m) throw new Error(`bad field ${field}`)
  return m[2] == null ? o[m[1]] : m[3] == null ? o[m[1]]?.[+m[2]] : o[m[1]]?.[+m[2]]?.[m[3]]
}
function set(o, field, v) {
  const m = field.match(/^(\w+)(?:\[(\d+)\](?:\.(\w+))?)?$/)
  if (m[2] == null) o[m[1]] = v; else if (m[3] == null) o[m[1]][+m[2]] = v; else o[m[1]][+m[2]][m[3]] = v
}
const GENDERED = /\b(he|she|his|her|him|hers|himself|herself)\b/gi
const words = s => (String(s).match(GENDERED) || []).map(w => w.toLowerCase())

/** Planned item for every id, from a given source of rows. */
function buildPlan(src) {
  const out = {}
  for (const p of PLAN) {
    const from = src[p.id].item
    const to = structuredClone(from)
    for (const e of p.edits) {
      if (get(from, e.field) !== e.from) throw new Error(`${p.id} ${e.field}: live text is not the planned "from"`)
      // An edit may only swap gendered words: same text with them masked.
      const mask = s => String(s).replace(GENDERED, '_')
      if (mask(e.from) !== mask(e.to)) throw new Error(`${p.id} ${e.field}: edit changes more than pronouns`)
      if (words(e.from).length !== words(e.to).length) throw new Error(`${p.id} ${e.field}: pronoun count changed`)
      set(to, e.field, e.to)
    }
    const k = from.choices.indexOf(from.correct_answer)
    if (k < 0 || to.choices.indexOf(to.correct_answer) !== k) throw new Error(`${p.id}: key is not the same option`)
    ;(from.distractor_rationales || []).forEach((d, i) => {
      if (from.choices.includes(d.choice) && !to.choices.includes(to.distractor_rationales[i].choice)) throw new Error(`${p.id}: rationale ${i} lost its choice`)
    })
    const allowed = ['prompt', 'choices', 'correct_answer', 'explanation', 'distractor_rationales']
    for (const key of new Set([...Object.keys(from), ...Object.keys(to)])) if (!same(from[key], to[key]) && !allowed.includes(key)) throw new Error(`${p.id}: ${key} would change`)
    out[p.id] = to
  }
  return out
}

const live = await rowsById(IDS)
const haveSnap = existsSync(SNAP)
const snapRows = haveSnap ? Object.fromEntries(JSON.parse(readFileSync(SNAP, 'utf8')).map(r => [r.id, r])) : null
const base = haveSnap ? snapRows : live
const plan = buildPlan(base)

const pending = IDS.filter(id => !same(live[id].item, plan[id]))
const done = IDS.filter(id => same(live[id].item, plan[id]))
const byCohort = {}
for (const p of PLAN) byCohort[p.cohort] = (byCohort[p.cohort] || 0) + 1
console.log(`items ${IDS.length} in ${new Set(PLAN.map(p => p.passage_group_id ?? p.id)).size} conversations ${JSON.stringify(byCohort)}`)
console.log(`field edits ${PLAN.reduce((n, p) => n + p.edits.length, 0)}; ${pending.length} pending, ${done.length} already applied`)
if (process.argv.includes('--show')) for (const p of PLAN) {
  console.log(`\n${p.id} [${p.cohort}] ${p.speakers}`)
  for (const e of p.edits) console.log(`  ${e.field}\n    - ${e.from}\n    + ${e.to}`)
}

const shaIds = PLAN.filter(shaMoves).map(p => p.id)
const all = await bindings(IDS), sha = await bindings(shaIds)
console.log(`\nbound to all ${IDS.length}: reviews ${all.reviews} (fresh ${all.reviewsFresh}), attacks ${all.attacks} (fresh ${all.attacksFresh})`)
console.log(`bound to the ${shaIds.length} content_sha-changing items: reviews fresh ${sha.reviewsFresh}/${sha.reviews}, attacks fresh ${sha.attacksFresh}/${sha.attacks} -> these go STALE (076/077).`)
console.log(`explanation/rationale-only items (${IDS.length - shaIds.length}) keep their evidence fresh.`)

if (!haveSnap) {
  if (done.length) { console.error('REFUSING: no snapshot but some rows already match the plan'); process.exit(2) }
  writeFileSync(SNAP, JSON.stringify(IDS.map(id => live[id]), null, 1) + '\n')
  console.log(`snapshot written: ${SNAP} (${IDS.length} full rows)`)
}
if (!WRITE) { console.log(`\nDRY RUN - ${pending.length} row(s) would change. --write only after owner sign-off.`); process.exit(0) }

// ── WRITE ──
const snap = Object.fromEntries(JSON.parse(readFileSync(SNAP, 'utf8')).map(r => [r.id, r]))
for (const id of pending) if (!same(live[id].item, snap[id].item)) {
  console.error(`REFUSING: ${id} live row no longer matches the snapshot`); process.exit(2)
}
for (const id of pending) {
  const { error } = await db.from('study_item_bank').update({ item: plan[id] }).eq('id', id)
  if (error) throw new Error(`${id}: ${error.message}`)
}
const after = await rowsById(IDS)
let bad = 0
for (const p of PLAN) {
  if (!same(after[p.id].item, plan[p.id])) { console.error(`MISMATCH after write: ${p.id}`); bad++ }
  if ((after[p.id].content_sha !== snap[p.id].content_sha) !== shaMoves(p)) { console.error(`content_sha ${shaMoves(p) ? 'unchanged' : 'changed'}: ${p.id}`); bad++ }
}
const post = await bindings(IDS)
console.log(`wrote ${pending.length}; re-read ${IDS.length}: ${bad} problem(s). Now fresh: reviews ${post.reviewsFresh}/${post.reviews}, attacks ${post.attacksFresh}/${post.attacks}`)
process.exit(bad ? 1 : 0)
